export function getLocationsByType(type) {
  if (type === 'Rooms') return toEntries(ROOMS, 'Room ');
  if (type === 'Public Area') return toEntries(PUBLIC_AREAS);
  if (type === 'Restaurant') return toEntries(RESTAURANTS);
  return [];
}
